# Что нужно сделать
# Задано положительное число x (x > 0). Ваша задача — преобразовать его
# в формат плавающей точки, то есть ‌
# ‌, где 1 ≤ a < 10. Обратите внимание, что x теперь больше нуля,
# а не больше единицы. Обеспечьте контроль ввода.

# Пример 1

# Введите число: 92345

# Формат плавающей точки: x = 9.2345 * 10 ** 4

# Пример 2

# Введите число: 0.0012

# Формат плавающей точки: x = 1.2 * 10 ** -3

def to_scientific_notation(number):
    count = 0
    while number >= 10:
        number /= 10
        count += 1
    while number < 1:
        number *= 10
        count -= 1
    return number, count


number = input("Введите число: ")

if number.replace('.', '', 1).isdigit() and float(number) > 0:
    number = float(number)
    a_num, b_num = to_scientific_notation(number)
    print(f"Формат плавающей точки: x = {a_num} * 10 ** {b_num}")
else:
    print("Ошибка: введите положительное число!")
