# Задача 2. Сокращения
# В одной компании наступили «тёмные времена», и сотрудников стали сокращать.
# Зарплаты сотрудников хранятся в списке из N этих самых зарплат.
# Зарплаты уже уволенных сотрудников обозначаются в списке числом 0.

# Напишите программу, которая запрашивает у пользователя количество
# сотрудников и их зарплаты, затем удаляет все элементы списка со
# значением 0 и выводит в консоль, сколько сотрудников осталось,
# а также их зарплаты. Дополнительный список использовать нельзя.

count_of_employees = int(input('Введите количество сотруднпиков: '))
salary_of_employees = []
for count in range(1, count_of_employees + 1):
    salary = int(input(f'Зарплата {count} сотрудника: '))
    if salary > 0:
        salary_of_employees.append(salary)

print(f'Осталось сотрудников: {len(salary_of_employees)}')
print(f'Зарплаты: {salary_of_employees}')

print(f'Максимальная зп {max(salary_of_employees)}')
print(f'Минимальная зп {min(salary_of_employees)}')